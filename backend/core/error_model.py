"""
RFC 7807 Problem Details Error Model & Custom Domain Exceptions.
Ensures standardized error reporting across all REST APIs.
"""
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field

class ProblemDetails(BaseModel):
    """RFC 7807 Compliant Problem Details Model"""
    type: str = Field("about:blank", description="URI reference identifying problem type")
    title: str = Field(..., description="Short, human-readable summary of the problem type")
    status: int = Field(..., description="HTTP status code generated by the origin server")
    detail: str = Field(..., description="Human-readable explanation specific to this occurrence")
    instance: Optional[str] = Field(None, description="URI reference identifying specific occurrence")
    error_code: str = Field(..., description="Machine-readable application specific error code")
    invalid_params: Optional[Dict[str, Any]] = Field(None, description="Validation field details if any")

class DomainException(Exception):
    """Base domain exception with RFC 7807 metadata"""
    def __init__(self, error_code: str, title: str, detail: str, status: int = 400, invalid_params: Optional[Dict[str, Any]] = None):
        super().__init__(detail)
        self.error_code = error_code
        self.title = title
        self.detail = detail
        self.status = status
        self.invalid_params = invalid_params

class ProductNotFoundException(DomainException):
    def __init__(self, product_id: str):
        super().__init__(
            error_code="PRODUCT_NOT_FOUND",
            title="Product Not Found",
            detail=f"The product with ID '{product_id}' was not found in the catalog.",
            status=404
        )

class OutOfStockException(DomainException):
    def __init__(self, product_id: str, requested: int, available: int):
        super().__init__(
            error_code="OUT_OF_STOCK",
            title="Inventory Insufficient",
            detail=f"Requested {requested} units for product '{product_id}', but only {available} units are available.",
            status=409,
            invalid_params={"productId": product_id, "requested": requested, "available": available}
        )

class InvalidQuantityException(DomainException):
    def __init__(self, detail: str = "Quantity must be greater than zero and less than or equal to 99."):
        super().__init__(
            error_code="INVALID_QUANTITY",
            title="Invalid Item Quantity",
            detail=detail,
            status=422
        )

class ConcurrentModificationException(DomainException):
    def __init__(self, current_version: int, client_version: int):
        super().__init__(
            error_code="CONCURRENT_MODIFICATION",
            title="Optimistic Concurrency Conflict",
            detail=f"Cart was modified by another session. Current version is {current_version}, but client submitted version {client_version}.",
            status=409,
            invalid_params={"currentVersion": current_version, "clientVersion": client_version}
        )

class EmptyCartException(DomainException):
    def __init__(self):
        super().__init__(
            error_code="EMPTY_CART",
            title="Empty Cart Checkout Attempt",
            detail="Cannot proceed to checkout with an empty shopping cart.",
            status=400
        )

class CouponException(DomainException):
    def __init__(self, code: str, detail: str, error_code: str = "COUPON_INVALID"):
        super().__init__(
            error_code=error_code,
            title="Coupon Application Error",
            detail=detail,
            status=422,
            invalid_params={"couponCode": code}
        )

class PaymentTimeoutException(DomainException):
    def __init__(self, transaction_id: str, elapsed_ms: int):
        super().__init__(
            error_code="PAYMENT_GATEWAY_TIMEOUT",
            title="Payment SLA Breach",
            detail=f"Payment transaction '{transaction_id}' timed out after {elapsed_ms}ms (SLA is 1500ms). Compensating saga rollback triggered.",
            status=504,
            invalid_params={"transactionId": transaction_id, "elapsedMs": elapsed_ms}
        )

class OrderNotFoundException(DomainException):
    def __init__(self, order_id: str):
        super().__init__(
            error_code="ORDER_NOT_FOUND",
            title="Order Not Found",
            detail=f"The order with ID '{order_id}' was not found.",
            status=404
        )

class VipAccessRequiredException(DomainException):
    def __init__(self, product_id: str, product_name: str = ""):
        super().__init__(
            error_code="VIP_SUBSCRIPTION_REQUIRED",
            title="VIP Subscriber Exclusive Product",
            detail=f"'{product_name or product_id}' is reserved exclusively for VIP subscribers. Please upgrade to a VIP plan to purchase this item.",
            status=403,
            invalid_params={"productId": product_id, "requiredTier": "VIP"}
        )

